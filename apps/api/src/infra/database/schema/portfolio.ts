import { sql } from 'drizzle-orm';
import type { AnyPgColumn } from 'drizzle-orm/pg-core';
import {
  check,
  index,
  integer,
  pgEnum,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import { adminUsers } from './admin';
import { masters } from './masters';
import { services } from './services';

/**
 * A master's portfolio (EPIC 19, issue #307,
 * [ADR-0045](docs/decisions/ADR-0045-master-portfolio.md)): posts of 1–10
 * photos, each photo re-encoded by the server into public WebP renditions.
 *
 * **Photos only.** ADR-0045 § 7 defers video, so there is no `kind` column, no
 * video key and no duration. The ADR that adds video adds them, with a default
 * of `image` for every row already here.
 *
 * **The schema makes illegal shapes unrepresentable; it does not run the
 * lifecycle.** Publishing a post when its last photo is ready, and failing it
 * when one fails, is one transaction in the portfolio module (#308).
 */

/**
 * A post's life:
 *
 * - `draft` — created, photos being uploaded.
 * - `processing` — submitted; the `media` queue is making renditions.
 * - `published` — every photo is `ready`; shown on the profile.
 * - `failed` — a photo could not be processed. Shown only to its master.
 * - `deleted` — the master deleted it. Hidden at once; the sweep (#311)
 *   deletes its renditions.
 *
 * An admin's removal is not a status: a removed post keeps `published` and
 * carries `removed_at` (ADR-0045 § 6), like a removed review.
 */
export const portfolioPostStatus = pgEnum('portfolio_post_status', [
  'draft',
  'processing',
  'published',
  'failed',
  'deleted',
]);

/**
 * One raw upload's life, shared by a post's photos and the avatar:
 *
 * - `awaiting_upload` — presigned, nothing behind the key yet. This row is the
 *   single-use guarantee a presigned URL does not give (ADR-0024).
 * - `uploaded` — confirmed: the real size and the sniffed type are known.
 * - `processing` — the `media` queue has it.
 * - `ready` — renditions written; the raw object is deleted (ADR-0045 § 5).
 * - `failed` — refused or undecodable; `failure_code` says which.
 */
export const mediaUploadStatus = pgEnum('media_upload_status', [
  'awaiting_upload',
  'uploaded',
  'processing',
  'ready',
  'failed',
]);

export const portfolioPosts = pgTable(
  'portfolio_posts',
  {
    /** UUID v7, generated by the application, as every other id here. */
    id: uuid('id').primaryKey(),

    /** The posting master. Never changes. */
    masterId: uuid('master_id')
      .notNull()
      .references(() => masters.id, { onDelete: 'restrict' }),

    /**
     * Optional, never blank. The one editable field (ADR-0045 § 3). Its length
     * is `PORTFOLIO_CAPTION_MAX_CHARS` (500), enforced at the API; the CHECK is
     * a 2000-character backstop, so raising the env var needs no migration.
     */
    caption: text('caption'),

    /**
     * Optional tag: one of the master's own services. Hidden while the master
     * no longer offers it (ADR-0045 § 3), so it is not cleared when they stop.
     */
    serviceId: uuid('service_id').references(() => services.id, { onDelete: 'restrict' }),

    status: portfolioPostStatus('status').notNull().default('draft'),

    /**
     * How many photos the post holds. Moved with a conditional UPDATE
     * (`… where media_count < :max`), the `orders.photo_count` pattern, so two
     * uploads racing for the last slot cannot both win. The limit is
     * `PORTFOLIO_MAX_ITEMS_PER_POST` (ADR-0045 § 4), enforced there and not
     * here, so raising it is configuration and not a migration.
     */
    mediaCount: integer('media_count').notNull().default(0),

    publishedAt: timestamp('published_at', { withTimezone: true }),
    deletedAt: timestamp('deleted_at', { withTimezone: true }),

    /** An admin's removal (ADR-0045 § 6): all three together, or none. */
    removedAt: timestamp('removed_at', { withTimezone: true }),
    removedByAdminId: uuid('removed_by_admin_id').references(() => adminUsers.id, {
      onDelete: 'restrict',
    }),
    removalReason: text('removal_reason'),

    /**
     * A removed post's evidence (ADR-0045 § 6): when its move finished —
     * copied to the private bucket, the public copies deleted and their CDN
     * URLs purged — and when the 30-day sweep deleted it. Both are
     * recorded so a failed move is found again, and a purged post is not.
     * A move that never finished is purged too, once its retention has passed
     * (#362), so `evidence_purged_at` does not need `evidence_moved_at`.
     */
    evidenceMovedAt: timestamp('evidence_moved_at', { withTimezone: true }),
    evidencePurgedAt: timestamp('evidence_purged_at', { withTimezone: true }),

    /**
     * When the move's copies reached the private bucket (#369), before the
     * public ones are deleted. A move that stops after it — at the CDN purge
     * — is still `pending_move`, but its photos are read from here.
     */
    evidenceCopiedAt: timestamp('evidence_copied_at', { withTimezone: true }),

    /**
     * When the sweep last tried to move or purge this post's evidence (#362).
     * Both steps take the least recently tried first, so a post that keeps
     * failing waits behind the others instead of filling every batch.
     */
    evidenceAttemptedAt: timestamp('evidence_attempted_at', { withTimezone: true }),

    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    /**
     * The profile feed (#310): one master's published, unremoved posts, newest
     * first, keyset-paged on `(published_at, id)`. Partial, so the index holds
     * exactly the rows a profile can show. Written as `sql` rather than
     * `.desc()`, which builds `DESC NULLS LAST` and cannot serve a bare
     * `ORDER BY … DESC` (#191).
     */
    index('portfolio_posts_feed_idx')
      .on(table.masterId, sql`${table.publishedAt} desc`, sql`${table.id} desc`)
      .where(sql`${table.status} = 'published' and ${table.removedAt} is null`),

    /**
     * The master's own list (#308) and an admin's list filtered by master
     * (#312): every status, newest first, keyset-paged on `(created_at, id)`.
     * Also the covering index for the `master_id` foreign key.
     */
    index('portfolio_posts_master_created_idx').on(
      table.masterId,
      sql`${table.createdAt} desc`,
      sql`${table.id} desc`,
    ),

    /** An admin's list across every master (#312), newest first. */
    index('portfolio_posts_created_idx').on(sql`${table.createdAt} desc`, sql`${table.id} desc`),

    /**
     * The sweep (#311): drafts left behind, failed posts and deleted ones
     * whose renditions are still to go, oldest first.
     */
    index('portfolio_posts_sweep_idx')
      .on(table.updatedAt)
      .where(sql`${table.status} in ('draft', 'failed', 'deleted')`),

    /**
     * Removed posts whose evidence is still to move or to purge
     * (ADR-0045 § 6, #311, #312). A purged post leaves the index, so the sweep
     * never re-reads it. Both steps sort what they find by its last attempt
     * (#362): the removals of one retention window, a few rows.
     */
    index('portfolio_posts_removed_idx')
      .on(table.removedAt)
      .where(sql`${table.removedAt} is not null and ${table.evidencePurgedAt} is null`),

    /** Foreign keys: nullable, and set on few rows. */
    index('portfolio_posts_service_idx')
      .on(table.serviceId)
      .where(sql`${table.serviceId} is not null`),
    index('portfolio_posts_removed_by_admin_idx')
      .on(table.removedByAdminId)
      .where(sql`${table.removedByAdminId} is not null`),

    check(
      'portfolio_posts_caption_length',
      sql`${table.caption} is null
          or (char_length(btrim(${table.caption})) >= 1 and char_length(${table.caption}) <= 2000)`,
    ),
    check('portfolio_posts_media_count_non_negative', sql`${table.mediaCount} >= 0`),
    check(
      'portfolio_posts_published_has_time',
      sql`${table.status} <> 'published' or ${table.publishedAt} is not null`,
    ),
    check(
      'portfolio_posts_deleted_has_time',
      sql`${table.status} <> 'deleted' or ${table.deletedAt} is not null`,
    ),
    /**
     * A removal is complete or absent: when, by whom, and why (#312 caps the
     * reason at 600 characters, as a review removal's).
     */
    check(
      'portfolio_posts_removal_shape',
      sql`(${table.removedAt} is null
             and ${table.removedByAdminId} is null
             and ${table.removalReason} is null)
          or (${table.removedAt} is not null
             and ${table.removedByAdminId} is not null
             and ${table.removalReason} is not null
             and char_length(btrim(${table.removalReason})) between 1 and 600)`,
    ),
    /**
     * **A removed post is never `deleted`.** Deleting is a master's act and
     * sends the post to the sweep, which would destroy the evidence and the
     * row the audit points at (ADR-0045 § 6). The API refuses it; this makes
     * it impossible.
     */
    check(
      'portfolio_posts_removed_not_deleted',
      sql`${table.removedAt} is null or ${table.status} <> 'deleted'`,
    ),
    /**
     * Evidence is only a removed post's. It may be purged without having
     * moved: past retention it is deleted wherever it is (#362). A move is
     * recorded only after its copy (#369).
     */
    check(
      'portfolio_posts_evidence_shape',
      sql`(${table.evidenceMovedAt} is null or ${table.removedAt} is not null)
          and (${table.evidencePurgedAt} is null or ${table.removedAt} is not null)
          and (${table.evidenceAttemptedAt} is null or ${table.removedAt} is not null)
          and (${table.evidenceCopiedAt} is null or ${table.removedAt} is not null)
          and (${table.evidenceMovedAt} is null or ${table.evidenceCopiedAt} is not null)`,
    ),
  ],
);

/**
 * The lifecycle shape both upload tables share: what is known at each step.
 * The renditions are the post photo's own (`portfolio_media`); an avatar's go
 * on `masters` and are checked there.
 */
function uploadShape(table: {
  status: AnyPgColumn;
  verifiedContentType: AnyPgColumn;
  rawSizeBytes: AnyPgColumn;
  failureCode: AnyPgColumn;
}) {
  return sql`(${table.status} = 'awaiting_upload'
                and ${table.verifiedContentType} is null
                and ${table.rawSizeBytes} is null
                and ${table.failureCode} is null)
             or (${table.status} in ('uploaded', 'processing', 'ready')
                and ${table.verifiedContentType} is not null
                and ${table.rawSizeBytes} is not null
                and ${table.rawSizeBytes} > 0
                and ${table.failureCode} is null)
             or (${table.status} = 'failed'
                and ${table.failureCode} is not null)`;
}

export const portfolioMedia = pgTable(
  'portfolio_media',
  {
    id: uuid('id').primaryKey(),

    /**
     * The post. `cascade` only matters to a hard delete, which only the sweep
     * does, after the post's own renditions are gone; a master's deletion is
     * a status, so the rows stay until then.
     */
    postId: uuid('post_id')
      .notNull()
      .references(() => portfolioPosts.id, { onDelete: 'cascade' }),

    /** 0-based place in the post, in the order the master chose. */
    position: integer('position').notNull(),

    /**
     * The raw upload's key in the **private** bucket: server-generated,
     * opaque, deleted from storage once the renditions exist (ADR-0045 § 5).
     * The column stays, as the record of which upload this was.
     */
    rawStorageKey: text('raw_storage_key').notNull(),
    declaredContentType: text('declared_content_type').notNull(),
    verifiedContentType: text('verified_content_type'),
    rawSizeBytes: integer('raw_size_bytes'),

    status: mediaUploadStatus('status').notNull().default('awaiting_upload'),

    /** Why it failed: a stable code (`too_large`, `undecodable`, …), never an error message. */
    failureCode: text('failure_code'),

    presignExpiresAt: timestamp('presign_expires_at', { withTimezone: true }).notNull(),

    /**
     * The renditions' keys in the **public** bucket
     * (`portfolio/<random>/thumb.webp` and `display.webp`). Never sent to a
     * client: the API turns them into URLs (ADR-0045 § 5).
     */
    thumbKey: text('thumb_key'),
    displayKey: text('display_key'),

    /** The `display` rendition's size, for laying out the viewer before it loads. */
    width: integer('width'),
    height: integer('height'),

    /** Both renditions' bytes together: what this photo costs in storage. */
    bytesTotal: integer('bytes_total'),

    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    /** One photo per place in a post; also the covering index for `post_id`. */
    uniqueIndex('portfolio_media_post_position_unique').on(table.postId, table.position),

    /** A key names exactly one row, forever. */
    uniqueIndex('portfolio_media_raw_storage_key_unique').on(table.rawStorageKey),

    /** The abandoned-upload sweep (#311): presigned and never uploaded. */
    index('portfolio_media_awaiting_upload_idx')
      .on(table.presignExpiresAt)
      .where(sql`${table.status} = 'awaiting_upload'`),

    /**
     * The stuck-processing sweep (#311): uploaded or processing for longer
     * than any job takes — a job lost after its last retry, or one BullMQ
     * failed for stalling without calling its handler.
     */
    index('portfolio_media_unfinished_idx')
      .on(table.updatedAt)
      .where(sql`${table.status} in ('uploaded', 'processing')`),

    check('portfolio_media_position_non_negative', sql`${table.position} >= 0`),
    check('portfolio_media_upload_shape', uploadShape(table)),
    /**
     * Renditions, by step:
     *
     * - `ready`: both keys, the size and the bytes, every one present. Each is
     *   tested for `is not null` explicitly, because `width > 0` on a null is
     *   null and a null CHECK passes.
     * - `processing` and `failed`: the keys may be written **before** the
     *   objects are, so a crash between upload and update, or a failure after
     *   upload, still leaves a record the sweep (#311) can delete from. Their
     *   size and bytes stay empty: those describe a finished rendition.
     * - `awaiting_upload` and `uploaded`: nothing yet.
     */
    check(
      'portfolio_media_renditions_shape',
      sql`(${table.status} = 'ready'
             and ${table.thumbKey} is not null
             and ${table.displayKey} is not null
             and ${table.width} is not null and ${table.width} > 0
             and ${table.height} is not null and ${table.height} > 0
             and ${table.bytesTotal} is not null and ${table.bytesTotal} > 0)
          or (${table.status} in ('processing', 'failed')
             and (${table.thumbKey} is null) = (${table.displayKey} is null)
             and ${table.width} is null
             and ${table.height} is null
             and ${table.bytesTotal} is null)
          or (${table.status} in ('awaiting_upload', 'uploaded')
             and ${table.thumbKey} is null
             and ${table.displayKey} is null
             and ${table.width} is null
             and ${table.height} is null
             and ${table.bytesTotal} is null)`,
    ),
  ],
);

/**
 * A master's avatar upload in flight (ADR-0045 § 8).
 *
 * **Its own table, not a `portfolio_media` row.** A post photo belongs to a
 * post (`post_id` is not null, and its position is unique in the post); an
 * avatar belongs to no post. Making `post_id` nullable to fit it would weaken
 * every post-photo invariant for one row per master.
 *
 * **The renditions are recorded here as well as on `masters`.** The profile
 * reads the current keys from `masters`, swapped in one update. This row keeps
 * every upload's own keys until `renditions_deleted_at`, so an avatar that was
 * replaced, removed, or never swapped in is found by the sweep (#311) and its
 * objects deleted, instead of living on in the public bucket.
 */
export const masterAvatarUploads = pgTable(
  'master_avatar_uploads',
  {
    id: uuid('id').primaryKey(),
    masterId: uuid('master_id')
      .notNull()
      .references(() => masters.id, { onDelete: 'restrict' }),
    rawStorageKey: text('raw_storage_key').notNull(),
    declaredContentType: text('declared_content_type').notNull(),
    verifiedContentType: text('verified_content_type'),
    rawSizeBytes: integer('raw_size_bytes'),
    status: mediaUploadStatus('status').notNull().default('awaiting_upload'),
    failureCode: text('failure_code'),
    presignExpiresAt: timestamp('presign_expires_at', { withTimezone: true }).notNull(),
    /** The 128 and 512 px renditions in the public bucket, written before their objects are. */
    thumbKey: text('thumb_key'),
    displayKey: text('display_key'),
    /** When the sweep deleted this upload's renditions, once they were no longer the avatar. */
    renditionsDeletedAt: timestamp('renditions_deleted_at', { withTimezone: true }),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    uniqueIndex('master_avatar_uploads_raw_storage_key_unique').on(table.rawStorageKey),

    /**
     * **One avatar upload in flight per master.** A second presign replaces
     * the first rather than minting another live write capability into the
     * bucket (the `order_photos_pending_upload_unique` reasoning).
     */
    uniqueIndex('master_avatar_uploads_in_flight_unique')
      .on(table.masterId)
      .where(sql`${table.status} in ('awaiting_upload', 'uploaded', 'processing')`),

    /** A master's uploads, finished ones too: the covering index for `master_id`. */
    index('master_avatar_uploads_master_idx').on(table.masterId, sql`${table.createdAt} desc`),

    /** Renditions still in storage: the sweep looks here for ones no longer the avatar (#311). */
    index('master_avatar_uploads_renditions_live_idx')
      .on(table.updatedAt)
      .where(sql`${table.thumbKey} is not null and ${table.renditionsDeletedAt} is null`),

    /** The abandoned-upload sweep (#311). */
    index('master_avatar_uploads_awaiting_upload_idx')
      .on(table.presignExpiresAt)
      .where(sql`${table.status} = 'awaiting_upload'`),

    /** The stuck-processing sweep (#311), as `portfolio_media_unfinished_idx`. */
    index('master_avatar_uploads_unfinished_idx')
      .on(table.updatedAt)
      .where(sql`${table.status} in ('uploaded', 'processing')`),

    check('master_avatar_uploads_upload_shape', uploadShape(table)),
    /**
     * Keys come as a pair, on an upload that got as far as processing, and
     * are written before their objects; `ready` has them. Deleted renditions
     * keep their keys as the record of what was deleted.
     */
    check(
      'master_avatar_uploads_renditions_shape',
      sql`(${table.thumbKey} is null) = (${table.displayKey} is null)
          and (${table.status} <> 'ready' or ${table.thumbKey} is not null)
          and (${table.thumbKey} is null or ${table.status} in ('processing', 'ready', 'failed'))
          and (${table.renditionsDeletedAt} is null or ${table.thumbKey} is not null)`,
    ),
  ],
);

export type PortfolioPostRow = typeof portfolioPosts.$inferSelect;
export type PortfolioMediaRow = typeof portfolioMedia.$inferSelect;
